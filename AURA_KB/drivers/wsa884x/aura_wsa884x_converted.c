static int wsa884x_spkr_event(struct snd_soc_dapm_widget *w,
			      struct snd_kcontrol *kcontrol, int event)
{
	struct snd_soc_component *component = snd_soc_dapm_to_component(w->dapm);
	struct wsa884x_priv *wsa884x = snd_soc_component_get_drvdata(component);

	switch (event) {
	case SND_SOC_DAPM_POST_PMU:
		mutex_lock(&wsa884x->sp_lock);
		wsa884x->pa_on = true;
		mutex_unlock(&wsa884x->sp_lock);

		switch (wsa884x->dev_mode) {
		case RECEIVER:
			snd_soc_component_write_field(component, WSA884X_CDC_PATH_MODE,
						      WSA884X_RXD_MODE_MASK,
						      WSA884X_RXD_MODE_HIFI);
			snd_soc_component_write_field(component, WSA884X_SPKR_PWM_CLK_CTL,
						      WSA884X_SPKR_PWM_FREQ_SEL_MASK,
						      WSA884X_SPKR_PWM_FREQ_F600KHZ);
			snd_soc_component_write_field(component, WSA884X_DRE_CTL_0,
						       WSA884X_DRE_PROG_DELAY_MASK, 0x0);
			break;
		case SPEAKER:
			snd_soc_component_write_field(component, WSA884X_CDC_PATH_MODE,
						      WSA884X_RXD_MODE_MASK,
						      WSA884X_RXD_MODE_NORMAL);
			snd_soc_component_write_field(component, WSA884X_SPKR_PWM_CLK_CTL,
						      WSA884X_SPKR_PWM_FREQ_SEL_MASK,
						      WSA884X_SPKR_PWM_FREQ_F300KHZ);
			snd_soc_component_write_field(component, WSA884X_DRE_CTL_0,
						       WSA884X_DRE_PROG_DELAY_MASK, 0x9);
			break;
		default:
			break;
		}

		if (wsa884x->port_enable[WSA884X_PORT_COMP])
			snd_soc_component_write_field(component, WSA884X_DRE_CTL_0,
						      WSA884X_DRE_OFFSET_MASK,
						      wsa884x->comp_offset);
		snd_soc_component_write_field(component, WSA884X_VBAT_ADC_FLT_CTL,
					      WSA884X_VBAT_ADC_COEF_SEL_MASK,
					      WSA884X_VBAT_ADC_COEF_F_1DIV16);
		snd_soc_component_write_field(component, WSA884X_VBAT_ADC_FLT_CTL,
					      WSA884X_VBAT_ADC_FLT_EN_MASK, 0x1);
		snd_soc_component_write_field(component, WSA884X_PDM_WD_CTL,
					      WSA884X_PDM_EN_MASK,
					      WSA884X_PDM_ENABLE);

		break;
	case SND_SOC_DAPM_PRE_PMD:
		snd_soc_component_write_field(component, WSA884X_VBAT_ADC_FLT_CTL,
					      WSA884X_VBAT_ADC_FLT_EN_MASK, 0x0);
		snd_soc_component_write_field(component, WSA884X_VBAT_ADC_FLT_CTL,
					      WSA884X_VBAT_ADC_COEF_SEL_MASK,
					      WSA884X_VBAT_ADC_COEF_F_1DIV2);
		snd_soc_component_write_field(component, WSA884X_PA_FSM_CTL,
					      WSA884X_GLOBAL_PA_EN_MASK, 0);
		snd_soc_component_write_field(component, WSA884X_PDM_WD_CTL,
					      WSA884X_PDM_EN_MASK, 0);
		mutex_lock(&wsa884x->sp_lock);
		wsa884x->pa_on = false;
		mutex_unlock(&wsa884x->sp_lock);
		break;
	}
	return 0;
}

