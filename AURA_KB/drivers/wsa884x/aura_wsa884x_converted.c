static int wsa884x_init(struct wsa884x_priv *wsa884x)
{
	struct regmap *regmap = wsa884x->regmap;
	int variant, version, ret;

	if (wsa884x->hw_init)
		return 0;

	ret = regmap_read(regmap, WSA884X_OTP_REG_0, &variant);
	if (ret)
		return ret;
	variant = variant & WSA884X_ID_MASK;

	ret = regmap_read(regmap, WSA884X_CHIP_ID0, &version);
	if (ret)
		return ret;

	switch (variant) {
	case WSA8840:
		dev_dbg(wsa884x->dev, "WSA884X Version 1_%d, Variant: WSA8840\n",
			version);
		break;
	case WSA8845:
		dev_dbg(wsa884x->dev, "WSA884X Version 1_%d, Variant: WSA8845\n",
			version);
		break;
	case WSA8842:
		dev_dbg(wsa884x->dev, "WSA884X Version 1_%d, Variant: WSA8842\n",
			version);
		break;
	case WSA8845_V2:
		dev_dbg(wsa884x->dev, "WSA884X Version 1_%d, Variant: WSA8845_V2\n",
			version);
		break;
	default:
		dev_warn(wsa884x->dev, "unknown variant: %d\n", variant);
		break;
	}

	wsa884x->comp_offset = COMP_OFFSET2;

	/* Initial settings */
	regmap_multi_reg_write(regmap, reg_init, ARRAY_SIZE(reg_init));

	if (variant == WSA8840 || variant == WSA8842) {
		wsa884x->comp_offset = COMP_OFFSET3;
		regmap_update_bits(regmap, WSA884X_DRE_CTL_0,
				   WSA884X_DRE_OFFSET_MASK,
				   wsa884x->comp_offset);
	}

	wsa884x->hw_init = true;

	return 0;
}

static int wsa884x_update_status(struct sdw_slave *slave,
				 enum sdw_slave_status status)
{
	struct wsa884x_priv *wsa884x = dev_get_drvdata(&slave->dev);

	if (status == SDW_SLAVE_UNATTACHED)
		wsa884x->hw_init = false;

	if (status == SDW_SLAVE_ATTACHED && slave->dev_num > 0)
		return wsa884x_init(wsa884x);

	return 0;
}

