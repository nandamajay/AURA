static void wsa884x_reset_assert(void *data)
{
	struct wsa884x_priv *wsa884x = data;

	if (wsa884x->sd_reset)
		reset_control_assert(wsa884x->sd_reset);
	else
		gpiod_direction_output(wsa884x->sd_n, 1);
}

