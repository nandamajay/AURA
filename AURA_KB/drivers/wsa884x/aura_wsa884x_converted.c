	struct snd_soc_component *comp = snd_kcontrol_chip(kcontrol);
	struct wsa884x_priv *data = snd_soc_component_get_drvdata(comp);
	struct soc_mixer_control *mixer = (struct soc_mixer_control *)kcontrol->private_value;
